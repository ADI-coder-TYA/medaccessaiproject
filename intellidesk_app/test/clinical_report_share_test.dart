import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:intellidesk_app/modules/diagnostics/models/diagnostic_session.dart';
import 'package:intellidesk_app/modules/diagnostics/models/risk_assessment.dart';
import 'package:intellidesk_app/modules/diagnostics/models/symptom_vector.dart';
import 'package:intellidesk_app/modules/diagnostics/providers/diagnostic_state_provider.dart';
import 'package:intellidesk_app/modules/diagnostics/ui/ClinicalReportShareSheet.dart';

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  const testAssessment = RiskAssessment(
    riskScore: 0.82,
    riskLevel: ClinicalRiskLevel.high,
    uncertaintyBounds: UncertaintyBounds(
      confidence: 0.91,
      ciLower: 0.78,
      ciUpper: 0.86,
      epistemicVariance: 0.0012,
      monteCarloSamples: 20,
    ),
    primaryDiagnosis: 'Acute Bronchospasm & Wheeze',
    differentialDiagnoses: [
      DifferentialDiagnosisItem(
        condition: 'Asthma Exacerbation',
        probability: 0.78,
        urgency: 'URGENT',
      ),
      DifferentialDiagnosisItem(
        condition: 'Acute Bronchitis',
        probability: 0.22,
        urgency: 'PROMPT_CARE',
      ),
    ],
    clinicalRecommendations: [
      'Inhaled bronchodilator therapy advised',
      'Urgent clinical auscultation by physician recommended',
    ],
    featureAttributions: [
      FeatureAttributionItem(
        featureName: 'Acoustic Wheeze / Stridor',
        category: 'AUDIO',
        contributionWeight: 0.42,
        percentageImpact: 42,
        description: 'High-frequency musical adventitious airway sound',
      ),
    ],
    requiresImmediatePhysicianReview: true,
  );

  final testSession = DiagnosticSession(
    id: 'scr_test_session_101',
    patientId: 'pt_john_doe',
    institutionId: 'inst_central',
    symptomVector: const SymptomVector(
      bodyLocation: 'Chest',
      painScale: 6,
      durationDays: 4,
      symptoms: ['cough', 'wheezing', 'shortness_of_breath'],
    ),
    riskAssessment: testAssessment,
    createdAt: DateTime.now(),
    updatedAt: DateTime.now(),
  );

  test('generateClinicalReportText builds formatted clinical report with all biomarkers', () {
    final stateProvider = DiagnosticStateProvider();
    final text = ClinicalReportShareSheet.generateClinicalReportText(
      assessment: testAssessment,
      stateProvider: stateProvider,
      session: testSession,
    );

    expect(text, contains('MEDACCESS AI — CLINICAL ASSESSMENT SUMMARY REPORT'));
    expect(text, contains('Session ID: scr_test_session_101'));
    expect(text, contains('Primary Diagnosis: Acute Bronchospasm & Wheeze'));
    expect(text, contains('HIGH RISK (82% Risk Score)'));
    expect(text, contains('Model Confidence: 91% (95% CI: 78% - 86%)'));
    expect(text, contains('Physician Review Required: YES (URGENT)'));
    expect(text, contains('Asthma Exacerbation: 78% probability [URGENT]'));
    expect(text, contains('1. Inhaled bronchodilator therapy advised'));
    expect(text, contains('Acoustic Wheeze / Stridor (42% impact)'));
    expect(text, contains('NOTICE: Generated by MedAccess AI Clinical Decision Support System'));
  });

  testWidgets('ClinicalReportShareSheet.show copies report text to Clipboard and renders bottom sheet', (tester) async {
    String? copiedClipboardText;
    tester.binding.defaultBinaryMessenger.setMockMethodCallHandler(
      SystemChannels.platform,
      (MethodCall methodCall) async {
        if (methodCall.method == 'Clipboard.setData') {
          copiedClipboardText = (methodCall.arguments as Map)['text'] as String?;
          return null;
        }
        return null;
      },
    );

    final stateProvider = DiagnosticStateProvider();

    await tester.pumpWidget(
      MaterialApp(
        home: Scaffold(
          body: Builder(
            builder: (context) => ElevatedButton(
              onPressed: () {
                ClinicalReportShareSheet.show(
                  context,
                  assessment: testAssessment,
                  stateProvider: stateProvider,
                  session: testSession,
                );
              },
              child: const Text('Open Share Sheet'),
            ),
          ),
        ),
      ),
    );

    // Tap button to trigger share
    await tester.tap(find.text('Open Share Sheet'));
    await tester.pumpAndSettle();

    // Verify clipboard was populated
    expect(copiedClipboardText, isNotNull);
    expect(copiedClipboardText, contains('MEDACCESS AI — CLINICAL ASSESSMENT SUMMARY REPORT'));
    expect(copiedClipboardText, contains('Acute Bronchospasm & Wheeze'));

    // Verify bottom sheet UI is visible
    expect(find.text('Share Clinical Report'), findsOneWidget);
    expect(find.text('Screening report automatically copied to clipboard!'), findsOneWidget);
    expect(find.text('Download Referral Letter (PDF)'), findsOneWidget);
    expect(find.text('Report Copied to Clipboard'), findsOneWidget);
  });
}
